"""
KTH Actions dataset for video prediction.

Loads pre-extracted frames according to clip lists generated by
scripts/generate_kth_splits.py. Standard protocol: 10 input frames,
20 target frames, 128x128 grayscale, persons 1-13/14-16/17-25 split.

If scripts/kth_to_npy.py has packed the frames (frames_uint8.npy and
frames_index.json next to the frames folder), they are read from that
memory-mapped file instead of decoding PNGs. Same values, much faster.
"""
import json
from pathlib import Path

import numpy as np
import torch
from torch.utils.data import Dataset
from PIL import Image


class KTHActions(Dataset):
    """
    KTH Actions video prediction dataset.
    
    Each sample returns (input_frames, target_frames):
        input_frames:  (input_len, 1, H, W) float32 in [0, 1]
        target_frames: (target_len, 1, H, W) float32 in [0, 1]
    """
    def __init__(
        self,
        frames_root: str | Path,
        clips_file: str | Path,
        input_len: int = 10,
        target_len: int = 20,
        image_size: int = 128,
    ):
        self.frames_root = Path(frames_root)
        self.input_len = input_len
        self.target_len = target_len
        self.seq_len = input_len + target_len
        self.image_size = image_size
        
        with open(clips_file, "r") as f:
            self.clips = [line.strip() for line in f if line.strip()]

        if not self.clips:
            raise ValueError(f"No clips found in {clips_file}")

        # packed frames, opened lazily in each DataLoader worker
        self.npy_path = self.frames_root.parent / "frames_uint8.npy"
        index_path = self.frames_root.parent / "frames_index.json"
        self.index = json.loads(index_path.read_text()) if index_path.exists() else None
        self._packed = None
    
    def __len__(self) -> int:
        return len(self.clips)
    
    def __getitem__(self, idx: int):
        clip_line = self.clips[idx]
        rel_path, start, end = clip_line.rsplit(" ", 2)
        start, end = int(start), int(end)
        
        if end - start != self.seq_len:
            raise ValueError(
                f"Clip length mismatch: expected {self.seq_len}, "
                f"got {end - start} at idx {idx}"
            )
        
        if self.index is not None and self.npy_path.exists():
            if self._packed is None:
                self._packed = np.load(self.npy_path, mmap_mode="r")
            offset, n_frames = self.index[rel_path]
            assert end <= n_frames, (rel_path, end, n_frames)
            frames = self._packed[offset + start:offset + end].astype(np.float32) / 255.0
            frames = frames[:, None]
        else:
            video_dir = self.frames_root / rel_path
            frames = np.zeros((self.seq_len, 1, self.image_size, self.image_size),
                              dtype=np.float32)
            for i, frame_idx in enumerate(range(start, end)):
                frame_path = video_dir / f"{frame_idx:04d}.png"
                img = np.array(Image.open(frame_path), dtype=np.float32) / 255.0
                frames[i, 0] = img
        
        input_frames = frames[:self.input_len]
        target_frames = frames[self.input_len:]
        
        return torch.from_numpy(input_frames), torch.from_numpy(target_frames)